// @layer scripts @kind generated-source
// Generates the split bug-fix feature flags from the Wave-1b catalog (plans/_bundle_settings.json):
//   - core/zelda3/src/features_bugfixes.h   (kFeatures1_* / kFeatures2_* C enums; #included by features.h)
//   - shared/features/bundle-fixes.generated.ts  (FeatureDef[] for the registry/UI)
//   - shared/features/bundle-flags.generated.json (id -> {flag,word,bit,sites,...} for the split-wave agents + bridge)
// Run: node scripts/build/gen-bundle-flags.mjs   (re-run if the catalog changes; outputs are generated, do not hand-edit)

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const catalog = JSON.parse(readFileSync(resolve(root, 'plans/_bundle_settings.json'), 'utf8'))
const settings = [...catalog.settings]

// --- Review corrections (plans/_bundle_review.json) ---------------------------
// 1) Dropped site: player.c:6378 save-menu lockout fix is distinct from the Link_Initialize bundle.
if (!settings.some((s) => s.id === 'saveMenuLockoutAfterMedallionFix')) {
  settings.push({
    id: 'saveMenuLockoutAfterMedallionFix',
    name: 'Fix save-menu lockout after medallion cast',
    userMessage: 'Fixes being locked out of the save menu when you die right after casting a medallion.',
    category: 'gameplay-affecting',
    bundleFlag: 'MiscBugFixes',
    sites: ['core/zelda3/src/player.c:6378'],
  })
}
// 2) Wrong line number: swamola gate is at sprite_main.c:15207 (a dropped leading digit).
for (const s of settings) s.sites = (s.sites || []).map((x) => x.replace('sprite_main.c:5207', 'sprite_main.c:15207'))
// 3) Category mismatch: the two "| 0x32" audio-only SFX fixes share one category.
for (const s of settings) if (s.id === 'giantMoldormKnockbackSfx' || s.id === 'giantMoldormWeaponTinkSfxFix') s.category = 'visual-only'

// --- Bit allocation: first 32 -> features1, remainder -> features2 -----------
const pascal = (id) => id.charAt(0).toUpperCase() + id.slice(1)
const allocated = settings.map((s, i) => {
  const word = i < 32 ? 1 : 2
  const n = i < 32 ? i : i - 32
  return { ...s, word, n, mask: 2 ** n, flag: `kFeatures${word}_${pascal(s.id)}` }
})

const banner = (tool) => `// GENERATED by scripts/build/gen-bundle-flags.mjs — do not edit by hand.\n// Source of truth: plans/_bundle_settings.json (Wave-1b catalog). ${tool}\n`

// --- C header ----------------------------------------------------------------
const emitEnum = (word) => {
  const rows = allocated.filter((a) => a.word === word)
  if (!rows.length) return ''
  const body = rows
    .map((a) => `  ${a.flag} = ${a.mask >>> 0}u,${' '.repeat(Math.max(1, 40 - a.flag.length))}// ${a.category}: ${a.name}`)
    .join('\n')
  return `// Enum values for kRam_Features${word}\nenum {\n${body}\n};\n`
}
const header = `#ifndef ZELDA3_FEATURES_BUGFIXES_H_\n#define ZELDA3_FEATURES_BUGFIXES_H_\n${banner('Each was bundled under MiscBugFixes/GameChangingBugFixes/WidescreenVisualFixes upstream; split per the settings plan.')}\n${emitEnum(1)}\n${emitEnum(2)}\n#endif  // ZELDA3_FEATURES_BUGFIXES_H_\n`
writeFileSync(resolve(root, 'core/zelda3/src/features_bugfixes.h'), header)

// --- TS registry entries -----------------------------------------------------
const tsEntry = (a) => `  {
    id: '${a.id}',
    label: ${JSON.stringify(a.name)},
    description: ${JSON.stringify(`Bundled under ${a.bundleFlag} upstream. Sites: ${(a.sites || []).join(', ')}`)},
    userMessage: ${JSON.stringify(a.userMessage)},
    group: 'Bug fixes',
    kind: 'features0-bit',
    origin: 'snesrev',
    bundleOrigin: '${a.bundleFlag}',
    flag: '${a.flag}',
    word: ${a.word},
    bit: ${a.mask >>> 0},
    default: false,
    requires: [],
    affectsVanillaParity: true,
    live: true,
  },`
const ts = `/* @layer shared @kind data */
${banner('FeatureDef entries for the 42 split bug-fix toggles.')}import type { FeatureDef } from './feature.type';

const BUNDLE_FIXES: FeatureDef[] = [
${allocated.map(tsEntry).join('\n')}
];

export { BUNDLE_FIXES };
`
writeFileSync(resolve(root, 'shared/features/bundle-fixes.generated.ts'), ts)

// --- JSON map (for split-wave agents + bridge) -------------------------------
const map = {}
for (const a of allocated) map[a.id] = { flag: a.flag, word: a.word, bit: a.mask >>> 0, bundleFlag: a.bundleFlag, category: a.category, sites: a.sites || [] }
writeFileSync(resolve(root, 'shared/features/bundle-flags.generated.json'), JSON.stringify({ total: allocated.length, flags: map }, null, 2))

console.log(`Generated ${allocated.length} split bug-fix flags (features1: ${allocated.filter((a) => a.word === 1).length}, features2: ${allocated.filter((a) => a.word === 2).length}).`)
